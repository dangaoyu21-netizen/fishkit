const 词到组 = new Map()
for (const [组, 词们] of Object.entries(组表)) {
  for (const 词 of 词们) 词到组.set(String(词).toLowerCase(), 组)
}

/** 一个词属于哪一组（不在表里就返回原词） */
export function 归组(词) {
  const 净 = String(词 || '').trim().toLowerCase()
  if (!净) return ''
  return 词到组.get(净) || String(词 || '').trim()
}

/** 这个词的同组词（含它自己；不在表里就只有它自己） */
export function 展开(词) {
  const 净 = String(词 || '').trim()
  if (!净) return []
  const 组 = 词到组.get(净.toLowerCase())
  if (!组) return [净]
  return [净, ...(组表[组] || []).filter((x) => x !== 净)]
}

/** 两个词算不算同义 */
export function 同义(a, b) {
  const 甲 = String(a || '').trim().toLowerCase()
  const 乙 = String(b || '').trim().toLowerCase()
  if (!甲 || !乙) return false
  if (甲 === 乙) return true
  const 组 = 词到组.get(甲)
  return Boolean(组 && 组 === 词到组.get(乙))
}
